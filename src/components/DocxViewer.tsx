import { useEffect, useRef, useState } from "react";
import { renderAsync } from "docx-preview";

interface DocxViewerProps {
  fileUrl: string;
  zoom?: number;
  onLoadSuccess?: (numPages: number) => void;
}

export function DocxViewer({ fileUrl, zoom = 1, onLoadSuccess }: DocxViewerProps) {
  const containerRef = useRef<HTMLDivElement>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let isMounted = true;
    
    async function loadDocx() {
      if (!containerRef.current) return;
      try {
        setLoading(true);
        setError(null);
        
        // Ensure container is empty before rendering new doc
        containerRef.current.innerHTML = "";
        
        const response = await fetch(fileUrl, { credentials: "include" });
        if (!response.ok) {
          let errorText = response.statusText;
          try {
            const errJson = await response.json();
            if (errJson.error) errorText = errJson.error;
          } catch(e) {
            // ignore JSON parse errors
          }
          throw new Error("Failed to fetch document: " + errorText);
        }
        
        const contentType = response.headers.get("content-type");
        if (contentType && contentType.includes("text/html")) {
          throw new Error("Received HTML instead of DOCX. The backend URL might be incorrect or returning an error page.");
        }
        
        const blob = await response.blob();
        
        if (isMounted && containerRef.current) {
          const renderFn = renderAsync;
          if (!renderFn) throw new Error("Could not find renderAsync in docx-preview module");
          
          await renderFn(blob, containerRef.current, undefined, {
            className: "docx-document",
            inWrapper: true,
            ignoreWidth: false,
            ignoreHeight: false,
            ignoreFonts: false,
            breakPages: true,
            ignoreLastRenderedPageBreak: true,
            experimental: true,
            trimXmlDeclaration: true,
            debug: false
          });
          
          if (isMounted) {
            // Count sections (pages) generated by docx-preview
            const pages = containerRef.current.querySelectorAll("section.docx").length || 1;
            if (onLoadSuccess) {
              onLoadSuccess(pages);
            }
          }
        }
      } catch (err: any) {
        if (isMounted) {
          console.error("Error rendering docx:", err);
          let errMsg = err.message || "Failed to render document";
          if (err instanceof TypeError) errMsg += " (TypeError)";
          setError(errMsg + " | Details: " + String(err));
        }
      } finally {
        if (isMounted) setLoading(false);
      }
    }
    
    loadDocx();
    
    return () => {
      isMounted = false;
    };
  }, [fileUrl]);

  return (
    <div className="w-full h-full relative overflow-auto rounded-xl flex flex-col items-center py-8">
      {loading && (
        <div className="absolute inset-0 flex items-center justify-center z-10">
          <div className="animate-pulse text-stone-500 font-medium p-12">Loading DOCX...</div>
        </div>
      )}
      {error && (
        <div className="absolute inset-0 flex flex-col items-center justify-center z-10 text-red-500 p-12">
          <p className="font-bold text-lg">Failed to render DOCX.</p>
          <p className="text-sm mt-2 opacity-80">{error}</p>
        </div>
      )}
      <div 
        ref={containerRef} 
        className="w-full docx-wrapper-container flex flex-col items-center transition-transform"
        style={{ zoom: zoom }}
      />
    </div>
  );
}
